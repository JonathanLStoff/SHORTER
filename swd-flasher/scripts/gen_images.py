"""Turn firmware/target_a.bin and target_b.bin into src/fw_images.c (a C byte array).

Runs automatically before every PlatformIO build; can also be run by hand.
Missing files become empty images (the flasher then refuses to write to a board).
The output file is only rewritten when its content changes, so builds stay incremental.
"""
import os

try:
    Import("env")  # noqa: F821  (SCons injects this when run as a PlatformIO extra script)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render(name):
    path = os.path.join(ROOT, "firmware", f"target_{name}.bin")
    data = open(path, "rb").read() if os.path.exists(path) else b""
    body = ",".join(
        ("\n" if i % 16 == 0 else "") + f"0x{b:02x}" for i, b in enumerate(data)
    )
    return (
        f"const unsigned char fw_{name}[] = {{{body if data else '0'}}};\n"
        f"const unsigned int fw_{name}_len = {len(data)};\n"
    )


out = "/* generated by scripts/gen_images.py - do not edit */\n" + render("a") + render("b")
dest = os.path.join(ROOT, "src", "fw_images.c")
old = open(dest).read() if os.path.exists(dest) else None
if old != out:
    open(dest, "w").write(out)
